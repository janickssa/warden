// Regenerate src/api-types.ts from the backend's OpenAPI schema (README 16 rule 7). `--check` fails if stale.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const backend = new URL("../../backend/", import.meta.url).pathname;
const schema = execFileSync("uv", ["run", "--quiet", "python", "-m", "warden.api.openapi"], { cwd: backend, encoding: "utf8" });
const dir = mkdtempSync(join(tmpdir(), "warden-openapi-"));
writeFileSync(join(dir, "openapi.json"), schema);
const out = execFileSync("node_modules/.bin/openapi-typescript", [join(dir, "openapi.json")], { encoding: "utf8" });
const text = "// Generated by scripts/api-types.mjs from the backend's OpenAPI schema. Do not edit.\n" + out;
const target = new URL("../src/api-types.ts", import.meta.url).pathname;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== text) { console.error("src/api-types.ts is stale: run pnpm api-types"); process.exit(1); }
} else writeFileSync(target, text);
