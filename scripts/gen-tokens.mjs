#!/usr/bin/env node
// Nocturne → design/tokens.json and the web app's CSS (README 17.2: styles.css is the source of truth).
//
// - design/tokens.json: every custom property in styles.css' :root, grouped, plus the status colours
//   (ok/warn/danger, README 17.2) with 100–900 OKLCH ramps on the neutral ramp's lightness scale.
//   Theme.swift (M8) is generated from the same file.
// - web/src/styles/nocturne.css: styles.css minus its Google Fonts @import (the dashboard fetches nothing
//   at runtime; fonts are self-hosted through next/font).
// - web/src/styles/status.css: the status colours as CSS variables.
// Run: node scripts/gen-tokens.mjs  (CI checks the outputs are current with --check)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(join(root, "design/nocturne/styles.css"), "utf8");
const block = css.slice(css.indexOf(":root {") + 7, css.indexOf("\n}", css.indexOf(":root {")));
const vars = {};
for (const m of block.replace(/\/\*[\s\S]*?\*\//g, "").matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)) vars[m[1]] = m[2].trim();

const group = (prefix) =>
  Object.fromEntries(Object.entries(vars).filter(([k]) => k.startsWith(prefix)).map(([k, v]) => [k.slice(prefix.length), v]));

// Neutral ramp lightness (OKLCH L of --color-neutral-100…900), shared by every status ramp.
const L = { 100: 0.971, 200: 0.93, 300: 0.869, 400: 0.779, 500: 0.68, 600: 0.579, 700: 0.48, 800: 0.381, 900: 0.29 };
const CHROMA = { 100: 0.25, 200: 0.45, 300: 0.7, 400: 0.9, 500: 1, 600: 0.95, 700: 0.8, 800: 0.62, 900: 0.45 };
const STATUS = { ok: [0.76, 0.15, 150], warn: [0.81, 0.13, 80], danger: [0.7, 0.18, 25] };
const status = {};
for (const [name, [l, c, h]] of Object.entries(STATUS)) {
  status[name] = { base: `oklch(${l} ${c} ${h})` };
  for (const step of Object.keys(L)) status[name][step] = `oklch(${L[step]} ${(c * CHROMA[step]).toFixed(3)} ${h})`;
}

const tokens = {
  $source: "design/nocturne/styles.css (generated by scripts/gen-tokens.mjs; do not edit)",
  color: group("color-"),
  status,
  font: { ...group("font-"), mono: '"JetBrains Mono", ui-monospace, monospace' },
  space: group("space-"),
  radius: group("radius-"),
  shadow: group("shadow-"),
};

const statusCss =
  "/* Generated by scripts/gen-tokens.mjs from design/tokens.json. Do not edit. */\n:root {\n" +
  Object.entries(status)
    .flatMap(([n, ramp]) => Object.entries(ramp).map(([k, v]) => `  --color-${n}${k === "base" ? "" : `-${k}`}: ${v};`))
    .join("\n") +
  `\n  --font-mono: var(--font-jetbrains, "JetBrains Mono"), ui-monospace, monospace;\n}\n`;

const nocturne =
  "/* Generated by scripts/gen-tokens.mjs from design/nocturne/styles.css (fonts @import removed). Do not edit. */\n" +
  css.replace(/^@import url\([^)]*fonts\.googleapis[^)]*\);\s*$/m, "");

const outputs = {
  "design/tokens.json": JSON.stringify(tokens, null, 2) + "\n",
  "web/src/styles/status.css": statusCss,
  "web/src/styles/nocturne.css": nocturne,
};
const check = process.argv.includes("--check");
let stale = false;
for (const [path, text] of Object.entries(outputs)) {
  const full = join(root, path);
  if (check) {
    let cur = "";
    try { cur = readFileSync(full, "utf8"); } catch {}
    if (cur !== text) { console.error(`stale: ${path} (run node scripts/gen-tokens.mjs)`); stale = true; }
  } else writeFileSync(full, text);
}
if (nocturne.includes("googleapis")) { console.error("nocturne.css still references Google Fonts"); process.exit(1); }
process.exit(stale ? 1 : 0);
