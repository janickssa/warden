"""Write Sources/WardenKit/Theme.swift from design/tokens.json (Nocturne + status colours, README 17.2).
Run from ios/: python3 scripts/gen-theme.py [--check]. Colours come only from here (README 16 rule 11)."""

import json
import math
import re
import sys
from pathlib import Path

ios = Path(__file__).resolve().parents[1]
tokens = json.loads((ios.parent / "design/tokens.json").read_text(encoding="utf-8"))


def hex_rgb(h: str) -> tuple[float, float, float]:
    h = h.lstrip("#")
    return tuple(int(h[i : i + 2], 16) / 255 for i in (0, 2, 4))  # type: ignore[return-value]


def oklch_rgb(text: str) -> tuple[float, float, float]:
    l, c, h = (float(x) for x in re.match(r"oklch\(([\d.]+) ([\d.]+) ([\d.]+)\)", text).groups())
    a, b = c * math.cos(math.radians(h)), c * math.sin(math.radians(h))
    l_ = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (l - 0.0894841775 * a - 1.2914855480 * b) ** 3
    lin = (
        4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
        -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
        -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_,
    )
    enc = lambda v: 12.92 * v if v <= 0.0031308 else 1.055 * v ** (1 / 2.4) - 0.055  # noqa: E731
    return tuple(min(1.0, max(0.0, enc(v))) for v in lin)  # type: ignore[return-value]


def swift(name: str, rgb: tuple[float, float, float], opacity: float = 1.0) -> str:
    r, g, b = (round(x, 4) for x in rgb)
    return f"    public static let {name} = Color(.sRGB, red: {r}, green: {g}, blue: {b}, opacity: {opacity})"


c = tokens["color"]
names = {
    "bg": "bg", "surface": "surface", "text": "text", "accent": "accent", "neutral-100": "neutral100",
    "neutral-200": "neutral200", "neutral-300": "neutral300", "neutral-400": "neutral400", "neutral-500": "neutral500",
    "neutral-600": "neutral600", "neutral-800": "neutral800", "neutral-900": "neutral900", "accent-200": "accent200",
    "accent-300": "accent300", "accent-700": "accent700", "accent-800": "accent800", "accent-900": "accent900",
}
lines = [
    "// Generated by ios/scripts/gen-theme.py from design/tokens.json. Do not edit.",
    "import SwiftUI",
    "",
    "public enum Theme {",
]
lines += [swift(n, hex_rgb(c[k])) for k, n in names.items()]
lines.append(swift("divider", hex_rgb(c["text"]), 0.16))
for k in ("ok", "warn", "danger"):
    lines.append(swift(k, oklch_rgb(tokens["status"][k]["base"])))
lines += ["}", ""]
out = "\n".join(lines)
target = ios / "Sources/WardenKit/Theme.swift"
if "--check" in sys.argv:
    if target.read_text(encoding="utf-8") != out:
        sys.exit("Theme.swift is stale: run python3 ios/scripts/gen-theme.py")
else:
    target.write_text(out, encoding="utf-8")
print("theme ok")
