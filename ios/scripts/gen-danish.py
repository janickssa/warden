"""Write Packages/WardenCore/Sources/WardenCore/Danish.swift from the dashboard's Danish (web/src/lib/da.ts)
plus the iPhone's own strings (danish-app.json). Run from ios/: python3 scripts/gen-danish.py [--check]."""

import json
import re
import sys
from pathlib import Path

ios = Path(__file__).resolve().parents[1]
web = (ios.parent / "web/src/lib/da.ts").read_text(encoding="utf-8")
LIT = r'"((?:[^"\\]|\\.)*)"'
table = {json.loads(f'"{k}"'): json.loads(f'"{v}"') for k, v in re.findall(LIT + r"\s*:\s*" + LIT, web)}
table.update(json.loads((ios / "danish-app.json").read_text(encoding="utf-8")))


def lit(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


lines = ["// Generated by ios/scripts/gen-danish.py from web/src/lib/da.ts and ios/danish-app.json. Do not edit.", "", "enum Danish {", "    static let table: [String: String] = ["]
lines += [f"        {lit(k)}: {lit(v)}," for k, v in sorted(table.items())]
lines += ["    ]", "}", ""]
out = "\n".join(lines)
target = ios / "Packages/WardenCore/Sources/WardenCore/Danish.swift"
if "--check" in sys.argv:
    if target.read_text(encoding="utf-8") != out:
        sys.exit("Danish.swift is stale: run python3 ios/scripts/gen-danish.py")
else:
    target.write_text(out, encoding="utf-8")
print(f"{len(table)} Danish strings")
